#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""把 web-src/index.html 以 gzip 内嵌为 C 头文件 src/web/editor_gz.h。

- 纯标准库（gzip）；gzip mtime=0、压缩级别 9，保证产物可复现。
- 生成的 EDITOR_GZ 由 HttpServer.cpp 直接以 Content-Encoding: gzip 发送，
  浏览器自动解压，设备侧无需运行时解压。
"""

import gzip
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / "web-src" / "index.html"
OUT = ROOT / "src" / "web" / "editor_gz.h"

BYTES_PER_LINE = 16


def main() -> None:
    raw = SRC.read_bytes()
    gz = gzip.compress(raw, compresslevel=9, mtime=0)

    lines = []
    lines.append("#pragma once")
    lines.append("#include <cstdint>")
    lines.append("")
    lines.append("// Auto-generated by tools/build_web_asset.py. Do not edit.")
    lines.append("// Source: web-src/index.html (gzip, mtime=0, level 9)")
    lines.append("static const unsigned int EDITOR_GZ_LEN = %d;" % len(gz))
    lines.append("static const unsigned char EDITOR_GZ[] = {")
    for i in range(0, len(gz), BYTES_PER_LINE):
        chunk = gz[i:i + BYTES_PER_LINE]
        lines.append("  " + " ".join("0x%02x," % b for b in chunk))
    lines.append("};")
    lines.append("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="ascii", newline="\n")

    print("source : %s (%d bytes)" % (SRC, len(raw)))
    print("gzip   : %d bytes (%.1f KB)" % (len(gz), len(gz) / 1024.0))
    print("header : %s" % OUT)


if __name__ == "__main__":
    main()
